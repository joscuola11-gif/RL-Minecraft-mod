#!/usr/bin/env python3
"""
Samples the outline of the baked Fennec mesh (fennec.bin) as ~200 points and writes
src/main/java/com/rlfennec/physics/CarHull.java. The game uses them to find the lowest point of the car in any
orientation, so a car lying on its roof / side / nose is drawn resting on the road instead of sunk into it.

    python3 tools/generate_hull.py

Needs numpy.
"""
import struct
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
MESH = ROOT / "src/main/resources/assets/rlfennec/models/entity/fennec.bin"
OUT = ROOT / "src/main/java/com/rlfennec/physics/CarHull.java"


def load_points():
    """-> (all points of the mesh, {wheel name: (pivot, lowest tread point)})"""
    data = MESH.read_bytes()
    magic, version, scale, count = struct.unpack_from("<iifi", data, 0)
    assert magic == 0x434E4E46 and version == 1
    off = 16
    pts = []
    wheels = {}
    for _ in range(count):
        (nl,) = struct.unpack_from("<H", data, off); off += 2
        name = data[off:off + nl].decode(); off += nl
        pivot = np.array(struct.unpack_from("<fff", data, off)); off += 12
        vc, ic = struct.unpack_from("<ii", data, off); off += 8
        verts = np.frombuffer(data, "<f4", vc * 8, off).reshape(vc, 8); off += vc * 32 + ic * 2
        p = verts[:, :3] + pivot
        pts.append(p)
        if name.endswith("_tread"):
            wheels[name] = (pivot, p[:, 1].min())
    return np.concatenate(pts), wheels


def main():
    points, wheels = load_points()
    n = 400  # directions on a sphere (Fibonacci), the farthest vertex in each one is part of the outline
    i = np.arange(n) + 0.5
    phi = np.arccos(1 - 2 * i / n)
    theta = np.pi * (1 + 5 ** 0.5) * i
    dirs = np.stack([np.cos(theta) * np.sin(phi), np.cos(phi), np.sin(theta) * np.sin(phi)], axis=1)
    hull = points[np.unique(np.argmax(points @ dirs.T, axis=0))]
    body = ",\n".join("        " + ", ".join(f"{c:.4f}F" for c in p) for p in hull)
    # wheel contact points: under the middle of every tread, order front right, front left, rear right, rear left
    order = ["wheel_fr_tread", "wheel_fl_tread", "wheel_br_tread", "wheel_bl_tread"]
    contacts = ",\n".join("        " + ", ".join(f"{c:.4f}F" for c in (wheels[n][0][0], wheels[n][1], wheels[n][0][2])) for n in order)
    OUT.write_text(f"""package com.rlfennec.physics;

/**
 * The shape of the car: {len(hull)} points on the outline of the model (x = nose, y = roof, z = right side, blocks above
 * the road for the upright car) and the four wheel contact points. Generated by tools/generate_hull.py. The physics
 * collides these points with the arena, so the hitbox is the real shape of the car in any orientation.
 */
public final class CarHull {{
    /** x, y, z of each outline point. */
    public static final float[] POINTS = {{
{body}
    }};

    /** x, y, z of the four wheel contacts: front right, front left, rear right, rear left. */
    public static final float[] WHEELS = {{
{contacts}
    }};

    private CarHull() {{
    }}
}}
""")
    print(f"wrote {OUT} ({len(hull)} points)")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""
Samples the outline of the baked Fennec mesh (fennec.bin) as ~200 points and writes
src/main/java/com/rlfennec/entity/FennecHull.java. The game uses them to find the lowest point of the car in any
orientation, so a car lying on its roof / side / nose is drawn resting on the road instead of sunk into it.

    python3 tools/generate_hull.py

Needs numpy.
"""
import struct
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
MESH = ROOT / "src/main/resources/assets/rlfennec/models/entity/fennec.bin"
OUT = ROOT / "src/main/java/com/rlfennec/entity/FennecHull.java"


def load_points():
    data = MESH.read_bytes()
    magic, version, scale, count = struct.unpack_from("<iifi", data, 0)
    assert magic == 0x434E4E46 and version == 1
    off = 16
    pts = []
    for _ in range(count):
        (nl,) = struct.unpack_from("<H", data, off); off += 2 + nl
        pivot = np.array(struct.unpack_from("<fff", data, off)); off += 12
        vc, ic = struct.unpack_from("<ii", data, off); off += 8
        verts = np.frombuffer(data, "<f4", vc * 8, off).reshape(vc, 8); off += vc * 32 + ic * 2
        pts.append(verts[:, :3] + pivot)
    return np.concatenate(pts)


def main():
    points = load_points()
    n = 400  # directions on a sphere (Fibonacci), the farthest vertex in each one is part of the outline
    i = np.arange(n) + 0.5
    phi = np.arccos(1 - 2 * i / n)
    theta = np.pi * (1 + 5 ** 0.5) * i
    dirs = np.stack([np.cos(theta) * np.sin(phi), np.cos(phi), np.sin(theta) * np.sin(phi)], axis=1)
    hull = points[np.unique(np.argmax(points @ dirs.T, axis=0))]
    body = ",\n".join("        " + ", ".join(f"{c:.4f}F" for c in p) for p in hull)
    OUT.write_text(f"""package com.rlfennec.entity;

/**
 * The outline of the car: {len(hull)} points of the model (x = nose, y = roof, z = right side, blocks above the road for the
 * upright car), generated by tools/generate_hull.py. Used to find where the lowest point of the car is when it
 * lies tilted on the road.
 */
final class FennecHull {{
    /** x, y, z of each point. */
    static final float[] POINTS = {{
{body}
    }};

    private FennecHull() {{
    }}
}}
""")
    print(f"wrote {OUT} ({len(hull)} points)")


if __name__ == "__main__":
    main()
